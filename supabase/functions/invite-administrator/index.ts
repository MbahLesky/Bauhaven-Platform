// invite-administrator
//
// Privileged operation (BAU-DB-002 section 20.2, BAU-UML section 10):
// invites a permanent or temporary administrator with a specific role and
// scope. Only callers holding `roles.assign` (organisation-scoped - see
// supabase/migrations/0010, only super_admin has it) may call this.
//
// Two cases:
//   - The invitee's email already has a Bauhaven profile (an existing
//     staff/participant gaining an additional administrative role): the
//     assignment is created immediately, no new Auth user or email needed.
//   - The invitee is new: a Supabase Auth invite email is sent (via
//     `inviteUserByEmail`, reusing the same secure, password-less mechanism
//     already used for participant invitations - no password is ever
//     generated by this app) with the admin invitation's raw token embedded
//     in the new user's metadata. The Flutter app calls
//     accept-admin-invitation automatically on that user's first sign-in.
//
// Deploy with: supabase functions deploy invite-administrator

// npm:, not jsr: - this function is deployed via the Management API's
// inline-source path (this machine has no working `supabase` CLI binary),
// which does not pre-bundle jsr: imports the way the CLI's deploy step
// does. jsr: silently produces a BOOT_ERROR ("Function failed to start")
// under that path - confirmed directly, not assumed - npm: resolves fine.
import { createClient, type SupabaseClient } from 'npm:@supabase/supabase-js@2';

interface InvitePayload {
  email: string;
  role_code: string;
  assignment_type: 'permanent' | 'temporary';
  scope_type: 'organisation' | 'offering' | 'cohort' | 'project' | 'content_domain' | 'asset_domain';
  scope_id?: string | null;
  access_valid_from?: string | null;
  access_valid_until?: string | null;
}

function jsonResponse(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { 'Content-Type': 'application/json' },
  });
}

async function sha256Hex(input: string): Promise<string> {
  const data = new TextEncoder().encode(input);
  const digest = await crypto.subtle.digest('SHA-256', data);
  return Array.from(new Uint8Array(digest))
    .map((b) => b.toString(16).padStart(2, '0'))
    .join('');
}

Deno.serve(async (req: Request) => {
  if (req.method !== 'POST') {
    return jsonResponse({ error: 'Method not allowed' }, 405);
  }

  const supabaseUrl = Deno.env.get('SUPABASE_URL');
  const serviceRoleKey = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY');
  if (!supabaseUrl || !serviceRoleKey) {
    return jsonResponse({ error: 'Server misconfiguration: missing Supabase service credentials.' }, 500);
  }

  const authHeader = req.headers.get('Authorization');
  if (!authHeader) {
    return jsonResponse({ error: 'Missing Authorization header.' }, 401);
  }

  const callerClient: SupabaseClient = createClient(supabaseUrl, serviceRoleKey, {
    global: { headers: { Authorization: authHeader } },
    auth: { autoRefreshToken: false, persistSession: false },
  });
  const { data: userData, error: userError } = await callerClient.auth.getUser();
  if (userError || !userData?.user) {
    return jsonResponse({ error: 'Invalid or expired session.' }, 401);
  }
  const callerId = userData.user.id;

  const admin: SupabaseClient = createClient(supabaseUrl, serviceRoleKey, {
    auth: { autoRefreshToken: false, persistSession: false },
  });

  // Uses public.has_permission_for(p_user_id, ...) - migration 0015 - not
  // private.has_permission(). The latter reads auth.uid() internally and
  // isn't exposed to PostgREST; called through this service-role `admin`
  // client (no session JWT for the real caller), that combination meant
  // this check has always failed, for every caller including super_admin.
  // See migration 0015 and the audit doc for the live confirmation.
  const { data: canAssign, error: permError } = await admin.rpc('has_permission_for', {
    p_user_id: callerId,
    p_code: 'roles.assign',
    p_scope_type: 'organisation',
    p_scope_id: null,
  });
  if (permError || !canAssign) {
    return jsonResponse({ error: 'Permission denied: roles.assign required.' }, 403);
  }

  let payload: InvitePayload;
  try {
    payload = await req.json();
  } catch {
    return jsonResponse({ error: 'Invalid JSON body.' }, 400);
  }

  const email = payload.email?.trim().toLowerCase();
  if (!email || !payload.role_code || !payload.scope_type) {
    return jsonResponse({ error: 'email, role_code and scope_type are required.' }, 400);
  }
  if (payload.scope_type !== 'organisation' && !payload.scope_id) {
    return jsonResponse({ error: 'scope_id is required for a non-organisation scope.' }, 422);
  }
  if (payload.assignment_type === 'temporary' && !payload.access_valid_until) {
    return jsonResponse({ error: 'access_valid_until is required for a temporary assignment.' }, 422);
  }

  const { data: role, error: roleError } = await admin
    .from('roles')
    .select('id, is_active')
    .eq('code', payload.role_code)
    .maybeSingle();
  if (roleError || !role || !role.is_active) {
    return jsonResponse({ error: `"${payload.role_code}" is not a grantable role.` }, 422);
  }

  // BR-006 "no self-escalation": an issuer without roles.assign at
  // organisation scope cannot reach this function at all (checked above).
  // Additionally, only a super_admin may grant super_admin/
  // organisation_admin themselves - grant authority is itself scoped, not
  // just gated by holding roles.assign at all.
  if (['super_admin', 'organisation_admin'].includes(payload.role_code)) {
    const { data: callerRoles } = await admin
      .from('user_role_assignments')
      .select('roles(code)')
      .eq('user_id', callerId)
      .eq('status', 'active');
    const isSuperAdmin = (callerRoles ?? []).some(
      (row: { roles: { code: string } | null }) => row.roles?.code === 'super_admin',
    );
    if (!isSuperAdmin) {
      return jsonResponse({ error: 'Only a super admin may grant this role.' }, 403);
    }
  }

  const validFrom = payload.access_valid_from ?? new Date().toISOString();
  const expiresAt = new Date(Date.now() + 7 * 24 * 60 * 60 * 1000).toISOString(); // invitation link expiry, 7 days

  const rawToken = crypto.randomUUID() + crypto.randomUUID();
  const tokenHash = await sha256Hex(rawToken);

  const { data: invitation, error: invitationError } = await admin
    .from('admin_invitations')
    .insert({
      email,
      role_id: role.id,
      assignment_type: payload.assignment_type,
      scope_type: payload.scope_type,
      scope_id: payload.scope_id ?? null,
      access_valid_from: validFrom,
      access_valid_until: payload.access_valid_until ?? null,
      token_hash: tokenHash,
      status: 'queued',
      issued_by: callerId,
      expires_at: expiresAt,
    })
    .select('id')
    .single();

  if (invitationError || !invitation) {
    return jsonResponse({ error: `Failed to create invitation: ${invitationError?.message}` }, 500);
  }

  const { data: existingProfile } = await admin
    .from('profiles')
    .select('id')
    .ilike('email', email)
    .maybeSingle();

  let existingUser = false;
  let userId: string | null = null;

  if (existingProfile) {
    // Existing Bauhaven identity gaining an additional role - no new Auth
    // user or email needed, the grant applies immediately.
    existingUser = true;
    userId = existingProfile.id;
    const { error: grantError } = await admin.from('user_role_assignments').insert({
      user_id: userId,
      role_id: role.id,
      assignment_type: payload.assignment_type,
      scope_type: payload.scope_type,
      scope_id: payload.scope_id ?? null,
      valid_from: validFrom,
      valid_until: payload.access_valid_until ?? null,
      status: new Date(validFrom) > new Date() ? 'pending' : 'active',
      granted_by: callerId,
    });
    if (grantError) {
      return jsonResponse({ error: `Failed to grant role: ${grantError.message}` }, 500);
    }
    await admin
      .from('admin_invitations')
      .update({ status: 'accepted', accepted_at: new Date().toISOString(), accepted_user_id: userId })
      .eq('id', invitation.id);
  } else {
    const { data: invitedUser, error: inviteError } = await admin.auth.admin.inviteUserByEmail(email, {
      data: { admin_invitation_token: rawToken },
      redirectTo: `${Deno.env.get('ADMIN_PORTAL_URL') || 'https://admin.bauhaven.com'}/auth/confirm?next=/set-password`,
    });
    if (inviteError || !invitedUser?.user) {
      await admin
        .from('admin_invitations')
        .update({ status: 'failed', delivery_status: inviteError?.message ?? 'invite_failed' })
        .eq('id', invitation.id);
      return jsonResponse({ error: `Failed to invite administrator: ${inviteError?.message}` }, 500);
    }
    userId = invitedUser.user.id;
    await admin
      .from('admin_invitations')
      .update({ status: 'sent' })
      .eq('id', invitation.id);
  }

  await admin.rpc('log_audit_event', {
    p_actor_id: callerId,
    p_action: 'admin_invitation.issued',
    p_entity_type: 'admin_invitation',
    p_entity_id: invitation.id,
    p_before: null,
    p_after: { email, role_code: payload.role_code, scope_type: payload.scope_type, existing_user: existingUser },
    p_outcome: 'success',
    p_metadata: {},
  });

  return jsonResponse({ ok: true, invitationId: invitation.id, existingUser, userId });
});
